const MAPS = {
  ind: INDICATOR_HELP,
  cat: CATEGORY_HELP,
  tf: TIMEFRAME_HELP,
  greed: GREED_HELP,
  gc: GREED_COMPONENT_HELP,
  screen: SCREEN_HELP,
};

/**
 * `"ind:rsi"` 같은 한 문자열로 사전을 찾는다. DOM 속성 하나에 담기 위해서다 —
 * 카드가 400ms 마다 다시 그려지므로 요소에 객체를 매달아 두면 매번 잃는다.
 *
 * @param {string} ref `<맵>:<키>`
 * @returns {{title: string, what: string, scale?: Array, note?: string, caveat?: string}|null}
 */
export function helpRef(ref) {
  const [map, key] = String(ref ?? '').split(':');
  return MAPS[map]?.[key] ?? null;
}

/** 사전에 정의된 모든 참조 문자열. 테스트가 누락을 확인하는 데 쓴다. */
export function allHelpRefs() {
  return Object.entries(MAPS).flatMap(([map, table]) =>
    Object.keys(table).map((key) => `${map}:${key}`),
  );
}
